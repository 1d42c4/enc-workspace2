use keyfile_core::Spec;
#[test]
fn standardized_ascon_kat_1() {
    let key: &[u8] = &[
        0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0A, 0x0B, 0x0C, 0x0D, 0x0E,
        0x0F,
    ];
    let nonce: &[u8] = &[
        0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0A, 0x0B, 0x0C, 0x0D, 0x0E,
        0x0F,
    ];
    let plain: &[u8] = &[];
    let aad: &[u8] = &[];
    let expected: &[u8] = &[
        0x44, 0x27, 0xD6, 0x4B, 0x8E, 0x1E, 0x14, 0x51, 0xFC, 0x44, 0x59, 0x60, 0xF0, 0x83, 0x9B,
        0xB0,
    ];
    assert_eq!(
        a10::App::encrypt(key, nonce, aad, plain)
            .unwrap()
            .as_slice(),
        expected
    );
    assert_eq!(
        a10::App::decrypt(key, nonce, aad, expected)
            .unwrap()
            .as_slice(),
        plain
    );
}
